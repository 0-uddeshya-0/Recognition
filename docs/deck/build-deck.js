function light(s) { s.background = { color: MIST }; }
function dark(s) { s.background = { color: INK }; }

// the product's mark: a rounded outline square with a cobalt square inside
function glyph(s, x, y, size, ring) {
  s.addShape(p.ShapeType.roundRect, {
    x, y, w: size, h: size, rectRadius: size * 0.26,
    fill: { color: "FFFFFF", transparency: 100 },
    line: { color: ring, width: 1.75 },
  });
  s.addShape(p.ShapeType.rect, {
    x: x + size * 0.28, y: y + size * 0.28, w: size * 0.44, h: size * 0.44,
    fill: { color: COBALT }, line: { color: COBALT, width: 0 },
  });
}

function title(s, text, opts = {}) {
  s.addText(text, {
    x: 0.62, y: opts.y ?? 0.52, w: 12.1, h: 0.9, margin: 0,
    fontFace: H, fontSize: opts.size ?? 34, bold: true,
    color: opts.color ?? INK, align: "left", valign: "middle",
  });
}

function kicker(s, text, color = COBALT) {
  s.addText(text.toUpperCase(), {
    x: 0.64, y: 0.24, w: 12, h: 0.3, margin: 0,
    fontFace: M, fontSize: 10.5, bold: true, charSpacing: 2, color, valign: "middle",
  });
}

function card(s, x, y, w, h, fill = PAPER) {
  s.addShape(p.ShapeType.roundRect, {
    x, y, w, h, rectRadius: 0.14,
    fill: { color: fill }, line: { color: "E3E9F5", width: 0.75 }, shadow: shadow(),
  });
}

