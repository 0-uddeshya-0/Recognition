"""The autonomous layer: one trigger in, merged artifacts out, nobody in between.

    brief ──▶ N candidate strategies ──▶ build each ──▶ verify each
                                                          │
                        merge the winner ◀── rank ◀───────┘

The human is at the *trigger*, never inside the run. Once a brief is sealed the
loop runs to a merged pull request with no approval step: the deterministic
verifier in `recognition.score` is the only gate, and `score.rank` -- not a person
and not a model -- picks which candidate wins.

Two candidate engines, same interface:

* ``local``  -- strategies are generated by deterministic heuristics here. Fast,
  free, always available; used for tests and as the fallback when Devin is
  unreachable. This is what makes the system demonstrable without burning ACU.
* ``devin``  -- each strategy becomes its own Devin session, working in the repo,
  running the verifier on itself, and pushing a branch. Slower, and the real
  product: the sessions do the engineering.

A run is reproducible: the same brief and the same strategy set produce the same
buildings, because everything between the plan and the artifacts is deterministic.
"""
from __future__ import annotations

import json
import subprocess
import sys
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any

from .contracts import ArchitectPlan, Adjacency, DesignBrief, Envelope, RoomSpec
from .score import Verdict, load_ruleset, rank, verdict, winner
from .translate import LayoutError, translate_to_file

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_RULES = REPO_ROOT / "rules" / "by" / "residential.yaml"


# --------------------------------------------------------------------------
# Strategies -- how sibling candidates differ
# --------------------------------------------------------------------------

@dataclass
class Strategy:
    """One way to satisfy the same brief.

    Candidates must differ *structurally*, not by random seed, or the fan-out is
    theatre: three sessions producing the same building prove nothing.
    """
    name: str
    label: str
    description: str
    aspect: float = 1.2          # envelope width : depth
    circulation: bool = True     # a dedicated hall spine, or rooms opening directly
    generosity: float = 1.0      # multiplier on requested room areas


STRATEGIES: list[Strategy] = [
    Strategy("compact", "Compact core",
             "Squarer envelope with a central hall spine. Least external wall per "
             "m2, so cheapest to build and to heat.",
             aspect=1.15, circulation=True, generosity=1.0),
    Strategy("linear", "Linear frontage",
             "Wider, shallower envelope. Every habitable room reaches an exterior "
             "wall, which makes the daylight rule easy to satisfy.",
             aspect=1.75, circulation=True, generosity=1.0),
    Strategy("open", "Open plan",
             "No dedicated corridor; living spaces connect directly. Converts "
             "circulation area into usable floor.",
             aspect=1.35, circulation=False, generosity=1.12),
]


def strategy_by_name(name: str) -> Strategy:
    for s in STRATEGIES:
        if s.name == name:
            return s
    raise KeyError(f"unknown strategy '{name}'; have {[s.name for s in STRATEGIES]}")


# --------------------------------------------------------------------------
# Brief -> ArchitectPlan (the `local` candidate engine)
# --------------------------------------------------------------------------

DEFAULT_AREAS = {          # Richtwerte, guidance tier -- never presented as law
    "living": 26.0, "kitchen": 12.0, "bedroom": 14.0, "bathroom": 8.0,
    "office": 12.0, "hall": 10.0, "utility": 6.0, "other": 10.0,
}


def plan_from_brief(brief: DesignBrief, strat: Strategy) -> ArchitectPlan:
    """Deterministically expand a brief into a plan under one strategy.

    No model is called. Room areas come from the brief where the client gave
    them and from published Richtwerte otherwise -- and because those are
    guidance, not law, the compliance gate will never block on them.
    """
    rooms: list[RoomSpec] = []
    n = 0
    for req in brief.rooms:
        for i in range(req.count):
            n += 1
            base = req.min_area_m2 or DEFAULT_AREAS.get(req.category, 12.0)
            label = req.label or _german(req.category)
            if req.count > 1:
                label = f"{label} {i + 1}"
            rooms.append(RoomSpec(
                id=f"R-{n:02d}", category=req.category, label=label,
                target_area_m2=round(base * strat.generosity, 1),
            ))

    hall_id: str | None = None
    if strat.circulation and not any(r.category == "hall" for r in rooms):
        n += 1
        hall_id = f"R-{n:02d}"
        rooms.append(RoomSpec(hall_id, "hall", "Flur",
                              round(DEFAULT_AREAS["hall"] * strat.generosity, 1)))
    elif strat.circulation:
        hall_id = next(r.id for r in rooms if r.category == "hall")

    # Envelope sized from the programme plus a circulation and wall allowance,
    # then shaped by the strategy's aspect ratio.
    need = sum(r.target_area_m2 for r in rooms) * 1.22
    depth = (need / strat.aspect) ** 0.5
    width = need / depth
    env = Envelope(width_m=round(width * 2) / 2, depth_m=round(depth * 2) / 2)

    adjacency = _adjacencies(rooms, hall_id)
    return ArchitectPlan(
        project=brief.project, envelope=env, rooms=rooms, adjacency=adjacency,
        storey_height_m=brief.storey_height_m, circulation_id=hall_id,
        accessibility_tier=brief.accessibility_tier,
        rationale=f"{strat.label}: {strat.description}",
    )


def _adjacencies(rooms: list[RoomSpec], hall_id: str | None) -> list[Adjacency]:
    """Everything opens off the hall; without one, chain through the living room.

    A bathroom is never reached through a bedroom -- that is the convention this
    codifies, and it is why adjacency is declared rather than inferred later.
    """
    if hall_id:
        return [Adjacency(hall_id, r.id) for r in rooms if r.id != hall_id]
    anchor = next((r for r in rooms if r.category == "living"), rooms[0])
    return [Adjacency(anchor.id, r.id) for r in rooms if r.id != anchor.id]


def _german(category: str) -> str:
    return {"living": "Wohnen", "kitchen": "Küche", "bedroom": "Schlafzimmer",
            "bathroom": "Bad", "office": "Büro", "hall": "Flur",
            "utility": "HWR", "other": "Raum"}.get(category, category.title())


# --------------------------------------------------------------------------
# Build + verify one candidate
# --------------------------------------------------------------------------

@dataclass
class Candidate:
    name: str
    label: str
    plan: ArchitectPlan | None = None
    out_dir: Path | None = None
    verdict: Verdict | None = None
    error: str = ""
    devin_session: str = ""
    pull_request: str = ""

    @property
    def ok(self) -> bool:
        return self.verdict is not None and self.verdict.ok

    def summary(self) -> dict[str, Any]:
        return {
            "name": self.name, "label": self.label,
            "ok": self.ok, "error": self.error,
            "devin_session": self.devin_session, "pull_request": self.pull_request,
            "verdict": self.verdict.to_dict() if self.verdict else None,
        }


def build_and_verify(plan: ArchitectPlan, out_dir: Path, *, name: str,
                     rules_path: Path = DEFAULT_RULES,
                     brief: DesignBrief | None = None,
                     viewable: bool = True) -> Verdict:
    """Plan -> DSL -> IFC -> compliance verdict. Every step deterministic.

    With `viewable`, also renders the sheets and the 3D mesh the Studio needs.
    Tests turn it off: geometry is the thing under test, rendering is not.
    """
    import recognition.model as M
    import recognition.rules as R

    out_dir.mkdir(parents=True, exist_ok=True)
    plan.write(out_dir / "plan.json")

    dsl = translate_to_file(plan, out_dir / "design.py")           # L3: zero tokens
    ifc_path = out_dir / "model.ifc"
    _exec_dsl(dsl, ifc_path)                                       # L4: geometry

    model = M.load(ifc_path)                                       # L5: the gate
    report = R.check(model, R.load_ruleset(rules_path))
    _doc, metas = load_ruleset(rules_path)

    v = verdict(report, metas, candidate=name,
                brief=(brief.to_dict() if brief else None),
                metrics=_metrics(plan, model))
    v.write(out_dir / "verdict.json")

    if viewable:
        _viewables(ifc_path, out_dir, plan.project, rules_path)
    return v


def _viewables(ifc_path: Path, out_dir: Path, project: str, rules_path: Path) -> None:
    """Sheets and the 3D mesh: everything a person needs to judge the result.

    Best-effort by design. A candidate is legal or not on the strength of its
    compliance verdict; a missing PNG must never turn a passing building into a
    failing one, so rendering problems are reported and swallowed.
    """
    from . import mesh
    from .cli import run as run_package
    try:
        run_package(ifc_path, out_dir / "pkg", rules_path, project, "")
    except Exception as e:                      # noqa: BLE001 - presentation only
        print(f"      (sheets unavailable: {type(e).__name__}: {str(e)[:90]})")
    try:
        mesh.write(ifc_path, out_dir / "mesh.json")
    except Exception as e:                      # noqa: BLE001 - presentation only
        print(f"      (3D mesh unavailable: {type(e).__name__}: {str(e)[:90]})")


def _exec_dsl(dsl_path: Path, ifc_path: Path) -> None:
    """Run the generated module in a subprocess so a bad candidate cannot take
    the orchestrator down with it."""
    ifc_path.parent.mkdir(parents=True, exist_ok=True)
    code = (
        f"import runpy,sys;"
        f"ns=runpy.run_path({str(dsl_path)!r});"
        f"ns['h'].write({str(ifc_path)!r})"
    )
    proc = subprocess.run([sys.executable, "-c", code], cwd=REPO_ROOT,
                          capture_output=True, text=True, timeout=300)
    if proc.returncode != 0 or not ifc_path.exists():
        raise RuntimeError(
            f"generated design failed to build an IFC:\n{proc.stderr[-1500:]}"
        )


def _metrics(plan: ArchitectPlan, model) -> dict[str, Any]:
    """Ranking inputs. Cheap, geometric, and free of judgement."""
    room_area = sum(s.area for s in model.spaces)
    circ = sum(s.area for s in model.spaces if s.category == "hall")
    env = plan.envelope.area_m2
    return {
        "envelope_m2": round(env, 2),
        "room_area_m2": round(room_area, 2),
        "usable_ratio": round((room_area - circ) / env, 4) if env else 0.0,
        "circulation_m2": round(circ, 2),
        "openings": len(model.doors) + len(model.windows),
        "rooms": len(model.spaces),
    }


# --------------------------------------------------------------------------
# The run
# --------------------------------------------------------------------------

@dataclass
class RunResult:
    project: str
    engine: str
    candidates: list[Candidate] = field(default_factory=list)
    winner: str = ""
    merged: str = ""
    critic: str = ""

    def to_dict(self) -> dict:
        return {
            "project": self.project, "engine": self.engine,
            "winner": self.winner, "merged": self.merged, "critic": self.critic,
            "candidates": [c.summary() for c in self.candidates],
        }

    def write(self, path: str | Path) -> Path:
        p = Path(path)
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(json.dumps(self.to_dict(), indent=2, ensure_ascii=False), encoding="utf-8")
        return p


def run_local(brief: DesignBrief, out_root: Path, *, strategies: list[Strategy] | None = None,
              rules_path: Path = DEFAULT_RULES, log=print) -> RunResult:
    """The full loop with deterministic candidate generation. No API, no cost."""
    brief.resolve_accessibility()
    brief.validate()
    strats = strategies or STRATEGIES
    res = RunResult(project=brief.project, engine="local")

    for strat in strats:
        c = Candidate(strat.name, strat.label)
        log(f"  · {strat.name}: {strat.description[:64]}…")
        try:
            plan = plan_from_brief(brief, strat)
            c.plan = plan
            c.out_dir = out_root / strat.name
            c.verdict = build_and_verify(plan, c.out_dir, name=strat.name,
                                         rules_path=rules_path, brief=brief)
            log(f"    {c.verdict.stamp()} — {c.verdict.coverage_line()}")
        except (LayoutError, RuntimeError, ValueError) as e:
            # A candidate that cannot be built is a legitimate outcome of
            # exploration, not a crash. Record it and keep the siblings running.
            c.error = f"{type(e).__name__}: {e}"
            log(f"    unbuildable — {c.error[:110]}")
        res.candidates.append(c)

    verdicts = [c.verdict for c in res.candidates if c.verdict]
    best = winner(verdicts)
    if best:
        res.winner = best.candidate
        log(f"\n  winner: {best.candidate} ({best.coverage_line()}) — chosen by the scorer, not a human")
    else:
        log("\n  no candidate passed the compliance gate")
    res.write(out_root / "run.json")
    return res


def ranked(res: RunResult) -> list[Verdict]:
    return rank([c.verdict for c in res.candidates if c.verdict])


