BUILDER_PROMPT = """\
You are the architect on a Bayern residential project. Produce ONE floor-plan
layout as an ArchitectPlan JSON object and return it via the structured output
tool. Do not write code, do not open a pull request, and do not push anything.

STRATEGY YOU MUST FOLLOW — "{label}"
{description}
Your sibling sessions are exploring different strategies. Yours must be
structurally distinct from theirs, not a variation in numbers.

THE BRIEF
{brief}

THE SHAPE YOU MUST RETURN — ArchitectPlan
  envelope: {{width_m, depth_m, external_wall_m: 0.30, internal_wall_m: 0.15}}
  rooms:    [{{id: "R-01", category, label, target_area_m2, exterior_wall}}]
  adjacency:[{{a: "R-03", b: "R-01", via: "door"}}]
  circulation_id: the id of the hall room, or null for an open plan
  storey_height_m, accessibility_tier, rationale

HARD CONSTRAINTS — a plan breaking any of these is rejected automatically
1. NO COORDINATES. Give areas and adjacencies only. Wall positions are computed
   downstream by deterministic code; anything you invent there is discarded.
2. category must be one of: bedroom, living, kitchen, bathroom, office, hall,
   utility, other.
3. Every room must be reachable: the adjacency graph must be connected. A
   bathroom is never reached through a bedroom.
4. Sum of target_area_m2 must fit the envelope with ~22% left for walls and
   circulation, or the plan is infeasible and will be thrown away.
5. Every habitable room (bedroom, living, kitchen, office) needs an exterior
   wall — BayBO Art. 45 (2) requires glazing of 1/8 of its floor area.
6. Do not quote or invent a building regulation. Compliance is judged by a
   deterministic engine against a cited ruleset; your job is the layout.

Return only the JSON object.
"""

CRITIC_PROMPT = """\
You are reviewing a floor plan that has already passed an automated compliance
gate. Assume the numbers are right; look for what a checker cannot see.

THE PLAN
{plan}

THE COMPLIANCE RESULT
{verdict}

Answer strictly as JSON: {{"verdict": "PASS"|"FAIL", "notes": "<your review>"}}
where FAIL means you found something that makes this unbuildable or unfit to
live in — a room you cannot furnish, a door that would swing into another, a
circulation route that does not work, an orientation that wastes the site.
Be specific and brief. Do not restate the compliance result back to me.
"""


def run_devin(brief: DesignBrief, out_root: Path, *,
              strategies: list[Strategy] | None = None,
              rules_path: Path = DEFAULT_RULES,
              max_acu: int | None = None, timeout_s: float = 1800,
              critic: bool = True, log=print) -> RunResult:
    """The real product: N Devin sessions plan in parallel, we build and judge.

    Devin returns an ArchitectPlan and never touches the repository. That is not
    a workaround for the missing write permission -- it is the safer split. The
    session cannot report its own success, because the artifacts it is judged on
    are produced here, by deterministic code, from the plan it handed back.
    """
    from .devin import DevinClient, SessionSpec, fan_out, wait_all

    brief.resolve_accessibility()
    brief.validate()
    strats = strategies or STRATEGIES
    res = RunResult(project=brief.project, engine="devin")
    client = DevinClient()

    brief_json = json.dumps(brief.to_dict(), indent=2, ensure_ascii=False)
    specs = [
        SessionSpec(
            name=s.name, strategy=s.name,
            prompt=BUILDER_PROMPT.format(label=s.label, description=s.description,
                                         brief=brief_json),
            tags=["recognition", "autopilot", f"strategy:{s.name}"],
            max_acu=max_acu,
        )
        for s in strats
    ]

    log(f"  starting {len(specs)} Devin sessions in parallel…")
    ids = fan_out(client, specs, structured_output=_plan_schema())
    for name, sid in ids.items():
        log(f"    {name:9} → {sid or 'FAILED TO START'}")

    def _tick(name: str, snap) -> None:
        log(f"    {name:9} … {snap.status}")

    results = wait_all(client, ids, timeout_s=timeout_s, on_update=_tick)

    for s in strats:
        c = Candidate(s.name, s.label)
        r = results.get(s.name)
        c.devin_session = r.session_id if r else ""
        if r is None or not r.produced_output:
            c.error = (r.error if r else "no result") or f"session ended in '{r.status}' with no plan"
            log(f"  · {s.name}: {c.error[:110]}")
            res.candidates.append(c)
            continue
        try:
            plan, out = _plan_with_repair(client, r, brief, s, timeout_s, log=log)
            c.plan = plan
            c.out_dir = out_root / s.name
            c.verdict = build_and_verify(plan, c.out_dir, name=s.name,
                                         rules_path=rules_path, brief=brief)
            log(f"  · {s.name}: {c.verdict.stamp()} — {c.verdict.coverage_line()}")
        except (LayoutError, RuntimeError, ValueError) as e:
            c.error = f"{type(e).__name__}: {e}"
            log(f"  · {s.name}: unbuildable — {c.error[:110]}")
        res.candidates.append(c)

    best = winner([c.verdict for c in res.candidates if c.verdict])
    if best:
        res.winner = best.candidate
        log(f"\n  winner: {best.candidate} — chosen by the scorer, not a human")
        if critic:
            res.critic = _run_critic(client, res, best, log=log)
    else:
        log("\n  no candidate passed the compliance gate")

    client.close()
    res.write(out_root / "run.json")
    return res


def _plan_with_repair(client, result, brief: DesignBrief, strat: Strategy,
                      timeout_s: float, *, attempts: int = 2, log=print) -> tuple[ArchitectPlan, dict]:
    """Validate the session's plan; on a contract error, hand the error back.

    This is the whole autonomy argument in miniature. The validator's message is
    written to be an instruction ("room R-04 target_area_m2 must be > 0"), so the
    session can repair itself without a human reading the traceback. No person
    sees this loop unless every attempt fails.
    """
    from .contracts import ContractError
    from .devin import wait_all

    payload = result.structured_output
    last_err = ""
    for attempt in range(1, attempts + 1):
        try:
            return _plan_from_output(payload, brief, strat, log=log), payload
        except ContractError as e:
            last_err = str(e)
            if attempt == attempts:
                break
            log(f"    {strat.name}: contract error, asking the session to repair "
                f"(attempt {attempt}/{attempts - 1})")
            log(f"      {last_err[:150]}")
            try:
                client.send_message(
                    result.session_id,
                    f"The plan you returned was rejected by the schema validator:\n\n"
                    f"  {last_err}\n\n"
                    f"Return the corrected ArchitectPlan JSON object only. Change nothing "
                    f"except what the error names."
                )
            except Exception as e2:            # noqa: BLE001 - repair is best effort
                log(f"      could not send repair request: {e2}")
                break
            nxt = wait_all(client, {strat.name: result.session_id},
                           timeout_s=min(timeout_s, 600)).get(strat.name)
            if not nxt or not nxt.structured_output:
                break
            payload = nxt.structured_output
    raise ValueError(f"plan rejected after {attempts} attempt(s): {last_err}")


def _plan_schema() -> dict:
    """The structured-output contract handed to every builder session."""
    return {
        "type": "object",
        "properties": {
            "envelope": {"type": "object"},
            "rooms": {"type": "array"},
            "adjacency": {"type": "array"},
            "circulation_id": {"type": ["string", "null"]},
            "storey_height_m": {"type": "number"},
            "accessibility_tier": {"type": "string"},
            "rationale": {"type": "string"},
        },
        "required": ["envelope", "rooms"],
    }


# Synonyms observed from real sessions. Normalising these is being liberal about
# vocabulary, not about meaning: each maps to exactly one term with no ambiguity.
# Anything genuinely wrong still fails validation and goes back for repair.
_VIA_SYNONYMS = {"opening": "open", "open_plan": "open", "openplan": "open",
                 "direct": "open", "doorway": "door", "passage": "open"}
_CATEGORY_SYNONYMS = {
    "bath": "bathroom", "wc": "bathroom", "toilet": "bathroom", "shower": "bathroom",
    "bed": "bedroom", "bedrooms": "bedroom", "sleeping": "bedroom",
    "livingroom": "living", "living_room": "living", "lounge": "living", "dining": "living",
    "corridor": "hall", "hallway": "hall", "flur": "hall", "circulation": "hall",
    "study": "office", "workroom": "office",
    "storage": "utility", "technical": "utility", "laundry": "utility", "hwr": "utility",
}


def normalise_agent_plan(payload: dict) -> tuple[dict, list[str]]:
    """Map known vocabulary variants onto the contract's terms.

    Returns the payload plus a list of what was rewritten, so normalisation is
    visible in the run log rather than being a silent correction.
    """
    notes: list[str] = []
    for a in payload.get("adjacency", []) or []:
        if not isinstance(a, dict):
            continue
        via = str(a.get("via", "door")).strip().lower()
        if via in _VIA_SYNONYMS:
            notes.append(f"adjacency via '{via}' → '{_VIA_SYNONYMS[via]}'")
            a["via"] = _VIA_SYNONYMS[via]
    for r in payload.get("rooms", []) or []:
        if not isinstance(r, dict):
            continue
        cat = str(r.get("category", "")).strip().lower().replace(" ", "_")
        if cat in _CATEGORY_SYNONYMS:
            notes.append(f"room {r.get('id')} category '{cat}' → '{_CATEGORY_SYNONYMS[cat]}'")
            r["category"] = _CATEGORY_SYNONYMS[cat]
        elif cat:
            r["category"] = cat
    return payload, notes


def _plan_from_output(out: dict, brief: DesignBrief, strat: Strategy,
                      log=None) -> ArchitectPlan:
    """Validate whatever the session returned. Never trust it unchecked."""
    from .contracts import load_plan
    payload = dict(out)
    payload.setdefault("project", brief.project)
    payload.setdefault("storey_height_m", brief.storey_height_m)
    payload.setdefault("accessibility_tier", brief.accessibility_tier)
    payload.setdefault("rationale", f"{strat.label}: {strat.description}")
    payload.pop("schema", None)
    payload, notes = normalise_agent_plan(payload)
    if notes and log:
        for n in notes:
            log(f"      normalised: {n}")
    return load_plan(payload)


def _run_critic(client, res: RunResult, best: Verdict, *, log=print) -> str:
    """A fourth session that reviews what the checker cannot see.

    Advisory by construction: it can annotate the winner, never overturn it. A
    model must not be able to veto a deterministic gate, in either direction.
    """
    from .devin import wait_all
    cand = next((c for c in res.candidates if c.verdict is best), None)
    if cand is None or cand.plan is None:
        return ""
    log("  critic: reviewing the winner…")
    try:
        sid = client.create_session(
            CRITIC_PROMPT.format(
                plan=json.dumps(cand.plan.to_dict(), indent=2, ensure_ascii=False)[:6000],
                verdict=json.dumps(best.to_dict()["findings"][:10], indent=2)[:3000],
            ),
            title=f"Recognition · critic · {res.project}",
            tags=["recognition", "autopilot", "critic"],
            structured_output={"type": "object",
                               "properties": {"verdict": {"type": "string"},
                                              "notes": {"type": "string"}},
                               "required": ["verdict", "notes"]},
        )
    except Exception as e:                     # noqa: BLE001 - advisory stage
        log(f"  critic unavailable: {e}")
        return ""
    out = wait_all(client, {"critic": sid}, timeout_s=900).get("critic")
    if out and out.structured_output:
        note = str(out.structured_output.get("notes", ""))[:1200]
        log(f"  critic says: {note[:160]}")
        return note
    return ""
